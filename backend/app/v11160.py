VERSION = APP_VERSION
STATUS_SCHEMA = "sc-workbench-interactive-graphing-linked-views-status/1.0"
VIEW_SCHEMA = "sc-workbench-mathematical-view-spec/1.0"

router = APIRouter(tags=["workbench-v11160-interactive-graphing-linked-mathematical-views"])


class GraphingRequest(BaseModel):
    operation: Literal[
        "function-plot",
        "parametric-plot",
        "polar-plot",
        "implicit-field",
        "linked-function-study",
    ]
    expression: Optional[str] = Field(default=None, max_length=20000)
    expressionY: Optional[str] = Field(default=None, max_length=20000)
    variable: str = Field(default="x", max_length=100)
    parameter: str = Field(default="t", max_length=100)
    xVariable: str = Field(default="x", max_length=100)
    yVariable: str = Field(default="y", max_length=100)
    domain: List[float] = Field(default_factory=lambda: [-10.0, 10.0], min_length=2, max_length=2)
    yDomain: List[float] = Field(default_factory=lambda: [-10.0, 10.0], min_length=2, max_length=2)
    samples: int = Field(default=401, ge=25, le=10000)
    gridSize: int = Field(default=121, ge=25, le=501)
    includeDerivative: bool = True
    includeIntegral: bool = False
    includeRoots: bool = True
    includeCriticalPoints: bool = True
    integralReference: float = 0.0
    linkGroup: str = Field(default="math-view-1", max_length=200)


class GraphingCalculationObjectRequest(BaseModel):
    calculationObjectRequest: UnifiedCalculationRequest
    graphing: GraphingRequest


def _hash(payload: Dict[str, Any]) -> str:
    return content_hash(payload)


def _finite_or_none(values):
    out = []
    for v in np.asarray(values).reshape(-1):
        f = float(v)
        out.append(f if np.isfinite(f) else None)
    return out


def _sample_expression(expression: str, symbol: sp.Symbol, domain, samples):
    expr = sp.sympify(expression, locals={str(symbol): symbol})
    fn = sp.lambdify(symbol, expr, modules="numpy")
    xs = np.linspace(float(domain[0]), float(domain[1]), int(samples))
    with np.errstate(all="ignore"):
        ys = np.asarray(fn(xs))
    if ys.ndim == 0:
        ys = np.full(xs.shape, float(ys))
    ys = np.real_if_close(ys).astype(float)
    return expr, xs, ys


def _roots_on_domain(expr, symbol, domain, xs, ys):
    roots = []
    fn = sp.lambdify(symbol, expr, modules="numpy")
    for i in range(len(xs)-1):
        y0, y1 = ys[i], ys[i+1]
        if not (np.isfinite(y0) and np.isfinite(y1)):
            continue
        if y0 == 0:
            roots.append(float(xs[i]))
            continue
        if y0 * y1 < 0:
            try:
                root = optimize.brentq(lambda z: float(fn(z)), float(xs[i]), float(xs[i+1]))
                if domain[0] <= root <= domain[1]:
                    roots.append(float(root))
            except Exception:
                pass
    dedup = []
    for r in roots:
        if not dedup or abs(r-dedup[-1]) > 1e-7:
            dedup.append(r)
    return dedup


def _critical_points(expr, symbol, domain):
    derivative = sp.diff(expr, symbol)
    points = []
    try:
        solved = sp.solveset(sp.Eq(derivative, 0), symbol, domain=sp.Interval(float(domain[0]), float(domain[1])))
        if isinstance(solved, sp.FiniteSet):
            for p in solved:
                if p.is_real:
                    points.append(float(sp.N(p)))
    except Exception:
        pass
    return sorted(set(round(p, 12) for p in points))


def _base_view(req: GraphingRequest, kind: str):
    return {
        "schema": VIEW_SCHEMA,
        "viewId": f"v11160-{kind}",
        "kind": kind,
        "linkGroup": req.linkGroup,
        "interaction": {
            "crosshair": True,
            "zoom": True,
            "pan": True,
            "linkedSelection": True,
            "linkedDomain": True,
        },
    }


def execute_graphing(req: GraphingRequest) -> Dict[str, Any]:
    op = req.operation
    verification: Dict[str, Any] = {}
    views: List[Dict[str, Any]] = []
    method = op

    if op in {"function-plot", "linked-function-study"}:
        if not req.expression:
            raise ValueError(f"{op} requires expression")
        x = sp.Symbol(req.variable, real=True)
        expr, xs, ys = _sample_expression(req.expression, x, req.domain, req.samples)

        primary = _base_view(req, "cartesian-function")
        primary["domain"] = {"x": list(map(float, req.domain))}
        primary["series"] = [{
            "seriesId": "f",
            "label": f"f({req.variable})",
            "expression": str(expr),
            "x": xs.tolist(),
            "y": _finite_or_none(ys),
        }]
        markers = []

        if req.includeRoots:
            roots = _roots_on_domain(expr, x, req.domain, xs, ys)
            markers.extend({"kind": "root", "x": r, "y": 0.0} for r in roots)
            verification["rootsOnDomain"] = roots

        if req.includeCriticalPoints:
            crit = _critical_points(expr, x, req.domain)
            fn = sp.lambdify(x, expr, modules="numpy")
            for c in crit:
                try:
                    markers.append({"kind": "critical-point", "x": c, "y": float(fn(c))})
                except Exception:
                    pass
            verification["criticalPointsOnDomain"] = crit

        primary["markers"] = markers
        views.append(primary)

        if req.includeDerivative:
            dexpr = sp.diff(expr, x)
            dfn = sp.lambdify(x, dexpr, modules="numpy")
            with np.errstate(all="ignore"):
                dys = np.asarray(dfn(xs))
            if dys.ndim == 0:
                dys = np.full(xs.shape, float(dys))
            dv = _base_view(req, "derivative")
            dv["domain"] = {"x": list(map(float, req.domain))}
            dv["series"] = [{
                "seriesId": "df",
                "label": f"d/d{req.variable} f",
                "expression": str(dexpr),
                "x": xs.tolist(),
                "y": _finite_or_none(dys),
            }]
            views.append(dv)

        if req.includeIntegral:
            a = sp.Float(req.integralReference)
            t = sp.Symbol("_t", real=True)
            integrand = expr.subs(x, t)
            anti = sp.integrate(integrand, (t, a, x))
            afn = sp.lambdify(x, anti, modules="numpy")
            with np.errstate(all="ignore"):
                ays = np.asarray(afn(xs))
            if ays.ndim == 0:
                ays = np.full(xs.shape, float(ays))
            iv = _base_view(req, "accumulated-integral")
            iv["domain"] = {"x": list(map(float, req.domain))}
            iv["series"] = [{
                "seriesId": "integral",
                "label": f"Integral from {req.integralReference}",
                "expression": str(anti),
                "x": xs.tolist(),
                "y": _finite_or_none(ays),
            }]
            views.append(iv)

        if op == "linked-function-study":
            table = _base_view(req, "linked-table")
            table["columns"] = [req.variable, "f"]
            table["rows"] = [
                {req.variable: float(a), "f": b}
                for a, b in zip(xs.tolist(), _finite_or_none(ys))
            ]
            views.append(table)
            method = "linked-cartesian-analysis-view-spec"

    elif op == "parametric-plot":
        if not req.expression or not req.expressionY:
            raise ValueError("parametric-plot requires expression and expressionY")
        t = sp.Symbol(req.parameter, real=True)
        ex, ts, xv = _sample_expression(req.expression, t, req.domain, req.samples)
        ey, ts2, yv = _sample_expression(req.expressionY, t, req.domain, req.samples)
        view = _base_view(req, "parametric")
        view["domain"] = {"parameter": list(map(float, req.domain))}
        view["series"] = [{
            "seriesId": "parametric",
            "parameter": ts.tolist(),
            "x": _finite_or_none(xv),
            "y": _finite_or_none(yv),
            "xExpression": str(ex),
            "yExpression": str(ey),
        }]
        views.append(view)
        verification["parameterGridsMatch"] = bool(np.array_equal(ts, ts2))

    elif op == "polar-plot":
        if not req.expression:
            raise ValueError("polar-plot requires expression")
        theta = sp.Symbol(req.parameter, real=True)
        expr, ts, rs = _sample_expression(req.expression, theta, req.domain, req.samples)
        xv = rs * np.cos(ts)
        yv = rs * np.sin(ts)
        view = _base_view(req, "polar")
        view["domain"] = {"parameter": list(map(float, req.domain))}
        view["series"] = [{
            "seriesId": "polar",
            "parameter": ts.tolist(),
            "radius": _finite_or_none(rs),
            "x": _finite_or_none(xv),
            "y": _finite_or_none(yv),
            "expression": str(expr),
        }]
        views.append(view)

    elif op == "implicit-field":
        if not req.expression:
            raise ValueError("implicit-field requires expression")
        x = sp.Symbol(req.xVariable, real=True)
        y = sp.Symbol(req.yVariable, real=True)
        expr = sp.sympify(req.expression, locals={req.xVariable: x, req.yVariable: y})
        fn = sp.lambdify((x, y), expr, modules="numpy")
        xv = np.linspace(float(req.domain[0]), float(req.domain[1]), req.gridSize)
        yv = np.linspace(float(req.yDomain[0]), float(req.yDomain[1]), req.gridSize)
        X, Y = np.meshgrid(xv, yv)
        with np.errstate(all="ignore"):
            Z = np.asarray(fn(X, Y))
        if Z.ndim == 0:
            Z = np.full(X.shape, float(Z))
        view = _base_view(req, "implicit-field")
        view["domain"] = {
            "x": list(map(float, req.domain)),
            "y": list(map(float, req.yDomain)),
        }
        view["field"] = {
            "expression": str(expr),
            "x": xv.tolist(),
            "y": yv.tolist(),
            "z": [
                [float(v) if np.isfinite(v) else None for v in row]
                for row in np.asarray(Z, dtype=float)
            ],
            "contourLevel": 0.0,
        }
        views.append(view)
        verification["gridShape"] = [int(Z.shape[0]), int(Z.shape[1])]
        method = "implicit-scalar-field-view-spec"

    else:
        raise ValueError(f"Unsupported graphing operation: {op}")

    result = {
        "viewSpecVersion": "1.0",
        "linkGroup": req.linkGroup,
        "views": views,
        "viewCount": len(views),
    }
    body = {
        "ok": True,
        "schema": VIEW_SCHEMA,
        "version": VERSION,
        "operation": op,
        "engine": "sympy-numpy-linked-view-spec",
        "runtime": "python",
        "method": method,
        "result": result,
        "verification": verification,
        "wordpressRequired": False,
    }
    body["resultHash"] = _hash(
        {k: v for k, v in body.items() if k not in {"ok", "resultHash"}}
    )
    return body


def calculation_object_extension(req: UnifiedCalculationRequest, graphing_req: GraphingRequest):
    obj = build_calculation_object(req)
    result = execute_graphing(graphing_req)
    obj["extensions"] = dict(obj.get("extensions") or {})
    obj["extensions"]["mathematicalViews"] = result
    obj["result"]["mathematicalViews"] = result["result"]
    obj["visualizations"] = list(obj.get("visualizations") or [])
    obj["visualizations"].append(result["result"])
    obj["executionPlan"]["mathematicalViews"] = {
        "runtime": "python",
        "engine": "sympy-numpy-linked-view-spec",
        "operation": graphing_req.operation,
        "method": result["method"],
        "samples": graphing_req.samples,
        "gridSize": graphing_req.gridSize if graphing_req.operation == "implicit-field" else None,
    }
    obj["verification"]["mathematicalViews"] = result["verification"]
    obj["provenance"]["mathematicalViewsResultHash"] = result["resultHash"]
    obj["calculationObjectHash"] = _hash(
        {k: v for k, v in obj.items() if k not in {"ok", "calculationObjectHash"}}
    )
    return obj


