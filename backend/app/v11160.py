"""Workbench v11.16.0 — Interactive Graphing & Linked Mathematical Views.

Produces renderer-neutral mathematical view specifications for Cartesian,
parametric, polar, implicit, and linked analytical views. Visualization data
is generated by the FastAPI backend; WordPress remains an optional proxy.
"""
from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional

import numpy as np
import sympy as sp
from fastapi import APIRouter
from pydantic import BaseModel, Field
from scipy import optimize

from .release import APP_VERSION, PRODUCT_KEY, RUNTIME_KIND
from .v1100 import UnifiedCalculationRequest, build_calculation_object
